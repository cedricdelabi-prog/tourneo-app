const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),ts=require('typescript');
const cache=new Map();
function load(nom){
 const file=path.resolve(__dirname,'..',nom.replace(/^@\//,'')+'.ts');
 if(cache.has(file))return cache.get(file).exports;
 const module={exports:{}};cache.set(file,module);
 const js=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
 new Function('require','module','exports',js)((id)=>id.startsWith('@/')?load(id):require(id),module,module.exports);
 return module.exports;
}
const {bilanCockpitTournoi,statutMatchCockpit,filtrerMatchsCockpit}=load('lib/cockpit-tournoi');
const {OPTIONS_V2}=load('lib/options-v2');
const options={...OPTIONS_V2,terrains:2,duree:10,repos:0,depart:''};
const m=(id,score1='',score2='',ordre=id)=>({id,equipe1Id:'e'+id*2,equipe2Id:'e'+(id*2+1),score1,score2,journee:1,ordre});
const matchs=[m(1,'13','7'),m(2,'0','0'),m(3,'13',''),m(4),m(5,'-1','0')];
const initial=JSON.stringify(matchs);
const bilan=bilanCockpitTournoi(matchs,[1,1,444],options);
assert.equal(bilan.total,5);
assert.equal(bilan.valides,1,'only known confirmed matches counted');
assert.equal(bilan.aValider,1,'0-0 is valid score awaiting explicit confirmation');
assert.equal(bilan.saisiesIncompletes,2,'partial or invalid scores require attention');
assert.equal(bilan.aJouer,1);
assert.equal(bilan.progression,20);
assert.equal(bilan.prioritaire?.match.id,2,'complete unconfirmed result first');
assert.equal(bilan.prioritaire?.statut,'aValider');
assert.equal(JSON.stringify(matchs),initial,'dashboard does not change scores');
const partiel=bilanCockpitTournoi(matchs,[1,2],options);
assert.equal(partiel.prioritaire?.match.id,3,'unfinished score before new match');
const aJouer=bilanCockpitTournoi([m(6),m(7)],[6],options);
assert.equal(aJouer.prioritaire?.match.id,7);
assert.equal(bilanCockpitTournoi([m(1,'1','1')],[1],options).prioritaire,null,'no action needed after every match validated');
assert.equal(bilanCockpitTournoi([],[],options).progression,0,'empty tournament never divides by zero');
assert.equal(statutMatchCockpit({...m(8),manches:[{score1:'2',score2:''}]},new Set()),'saisieIncomplet','started multi-set score is incomplete');
assert.equal(statutMatchCockpit(m(9,'3','2'),new Set([9])),'valide','confirmed status is authoritative');
const inverse=[m(100,'','','2' ),m(101,'5','4',1)];
const prio=bilanCockpitTournoi(inverse,[],options);
assert.equal(prio.liste[0].match.id,101,'planning order uses match order rather than input order');
assert.equal(prio.prioritaire?.match.id,101);
const planInvalide=bilanCockpitTournoi(matchs,[1],{...options,terrains:0});
assert.equal(planInvalide.total,5,'invalid planning cannot hide organizer priorities');
assert.equal(planInvalide.prioritaire?.match.id,2);
const equipes=[{id:'e2',nom:'Équipe Étoile'},{id:'e3',nom:'Les Bleus'},{id:'e4',nom:'Partenaires'},{id:'e5',nom:'Club Nord'}];
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'aValider','',null,equipes).map(x=>x.match.id),[2],'only entered scores awaiting validation');
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'saisieIncomplet','',null,equipes).map(x=>x.match.id),[3,5],'incomplete score queue follows the planning');
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'aJouer','',null,equipes).map(x=>x.match.id),[4],'upcoming fixtures only');
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'valide','',null,equipes).map(x=>x.match.id),[1],'only validated fixtures');
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'tous','etoile',null,equipes).map(x=>x.match.id),[1],'accent-insensitive team name search');
assert.deepEqual(filtrerMatchsCockpit(bilan.liste,'tous','BLEUS',null,equipes).map(x=>x.match.id),[1],'case-insensitive search');
assert.ok(filtrerMatchsCockpit(bilan.liste,'tous','2',null,equipes).some(x=>x.match.id===2),'numeric match ID search');
const terrainUn=bilan.liste.find(x=>x.creneau)?.creneau?.terrain;
if(terrainUn)assert.ok(filtrerMatchsCockpit(bilan.liste,'tous','',terrainUn,equipes).every(x=>x.creneau?.terrain===terrainUn),'court filter uses actual scheduled assignment');
assert.equal(filtrerMatchsCockpit(bilan.liste,'aValider','impossible',null,equipes).length,0,'combined filters never modify matches');
assert.equal(JSON.stringify(matchs),initial,'filtering does not change any results');
const component=fs.readFileSync(path.resolve(__dirname,'../components/ProchaineActionTournoi.tsx'),'utf8');
assert.ok(component.includes('tourneo:voir-match'),'dashboard opens the matching score card');
assert.ok(component.includes('surImprevu'),'incident access is integrated');
const planningSource=fs.readFileSync(path.resolve(__dirname,'../components/PlanningTournoi.tsx'),'utf8');
assert.ok(planningSource.includes("tourneo:voir-match"),'planner receives direct navigation to a match');
assert.ok(planningSource.includes("filtrerMatchsCockpit("),'planner uses non-mutating pure filters');
assert.ok(planningSource.includes("Effacer les filtres"),'filters have an explicit reset button');
console.log('Tourneo V2 cockpit : validated scores, pending validation, incomplete entries, planning order, actions and safe fallback : OK');
