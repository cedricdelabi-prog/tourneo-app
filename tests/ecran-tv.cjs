const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
const m={exports:{}};new Function('require','module','exports',ts.transpileModule(fs.readFileSync('lib/ecran-tv.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(require,m,m.exports);
const {normaliserTV,pagesTV,appelTV,statutMatchTV,repriseSonoreDansDelai,pageCouranteTV,statistiquesTV,filtrerMatchsTV}=m.exports;
assert.deepEqual(normaliserTV(null),{secondes:15,pause:false,message:'',appel:null,defilement:true,repriseA:null,afficherSponsors:true,pageSponsors:false,afficherMatchs:true,afficherClassement:true,filtreMatchs:'tous',pageManuelle:0,debutDefilement:0});
assert.equal(normaliserTV({secondes:-50,message:'a'.repeat(200)}).secondes,8);
assert.equal(normaliserTV({secondes:Infinity}).secondes,15);
assert.equal(normaliserTV({defilement:false}).defilement,false,'organizer may disable auto-scroll');
assert.equal(normaliserTV({afficherSponsors:false}).afficherSponsors,false,'organizer may hide sponsors');
assert.equal(normaliserTV({pageSponsors:true}).pageSponsors,true,'organizer may show a dedicated sponsor slide');
assert.equal(normaliserTV({pageSponsors:'yes'}).pageSponsors,false,'invalid sponsor setting is rejected');
assert.equal(normaliserTV({afficherMatchs:false}).afficherMatchs,false);
assert.equal(normaliserTV({afficherClassement:false}).afficherClassement,false);
assert.equal(normaliserTV({filtreMatchs:'aValider'}).filtreMatchs,'aValider');
assert.equal(normaliserTV({filtreMatchs:'hacked'}).filtreMatchs,'tous');
assert.equal(normaliserTV({pageManuelle:4}).pageManuelle,4,'manual TV page is synchronized');
assert.equal(normaliserTV({pageManuelle:-1}).pageManuelle,0,'manual page cannot be negative');
assert.equal(normaliserTV({debutDefilement:1730000000000}).debutDefilement,1730000000000,'clock origin shared between windows');
assert.equal(normaliserTV({debutDefilement:-10}).debutDefilement,0,'reject negative clock origin');
const synchronise=normaliserTV({debutDefilement:10000,secondes:10,pageManuelle:2});
assert.equal(pageCouranteTV(synchronise,10000),2,'start from chosen slide');
assert.equal(pageCouranteTV(synchronise,19999),2,'slide stays active until next interval');
assert.equal(pageCouranteTV(synchronise,20000),3,'next slide at interval boundary');
assert.equal(pageCouranteTV(synchronise,40000),5,'both tabs use same deterministic count');
assert.equal(pageCouranteTV({...synchronise,pause:true},40000),2,'pause freezes page');
assert.equal(pageCouranteTV({...synchronise,defilement:false},40000),2,'manual navigation freezes page');
assert.equal(pageCouranteTV({...synchronise,debutDefilement:40000,pageManuelle:5},40000),5,'resume without skipping chosen page');

assert.equal(normaliserTV({pause:true,repriseA:1730000000000}).pause,true);
assert.equal(normaliserTV({message:'a'.repeat(200)}).message.length,180);
const liste=Array.from({length:35},(_,id)=>({id,equipe1Id:'a',equipe2Id:'b',journee:1,score1:'',score2:''}));
assert.deepEqual(pagesTV(liste).flat(),liste,'every match remains visible, including last page');
assert.equal(pagesTV(liste).at(-1).length,5);
assert.equal(appelTV(liste,[3],3),undefined,'never call a validated match');
assert.equal(appelTV(liste,[],3).id,3);
assert.equal(appelTV(liste,[],900),undefined,'cancelled match cannot remain called');
assert.equal(statutMatchTV({...liste[0],score1:'0',score2:'13'},[]),'À valider');
const demo=[{...liste[0],id:11},{...liste[1],id:12,score1:'2',score2:'1'},{...liste[2],id:13,score1:'0',score2:'0'}];
const stat=statistiquesTV(demo,[13]);
assert.deepEqual(stat,{total:3,aJouer:1,aValider:1,valides:1},'consistent organizer counts');
assert.equal(filtrerMatchsTV(demo,[13],'aJouer')[0].id,11);
assert.equal(filtrerMatchsTV(demo,[13],'aValider')[0].id,12);
assert.equal(filtrerMatchsTV(demo,[13],'valides')[0].id,13);
assert.deepEqual(filtrerMatchsTV(demo,[13],'tous'),demo);
assert.equal(demo.length,3,'TV filters never mutate original matches');
assert.equal(appelTV([{...liste[0],score1:'0',score2:'13'}],[],0),undefined);
assert.equal(repriseSonoreDansDelai(10000,10000),true,'beep at scheduled return');
assert.equal(repriseSonoreDansDelai(20000,10000),true,'beep within ten seconds');
assert.equal(repriseSonoreDansDelai(20001,10000),false,'no stale beep');
assert.equal(repriseSonoreDansDelai(9999,10000),false,'no early beep');
assert.equal(repriseSonoreDansDelai(20000,null),false,'no alert without return time');
console.log('TV : pagination complète, réglages bornés, appels explicites et retrait des matchs terminés : OK');
