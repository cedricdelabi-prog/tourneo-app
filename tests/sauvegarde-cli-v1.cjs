'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const s=fs.readFileSync('scripts/sauvegarder-v1-prive.ps1','utf8');
const expected=['gjtxlzhfqcecyfciyllc','--role-only','--data-only','--schema','auth,storage','--use-copy','Get-FileHash','sha256','SAUVEGARDER'];
for(const marker of expected)assert.ok(s.includes(marker),'Backup script is missing '+marker);
assert.match(s,/Join-Path \$env:USERPROFILE/,'Dump files must be outside the repository');
assert.match(s,/fichierRestaurationValide=\$false/);
assert.match(s,/function Executer-Supabase/);
const commandes=s.split(/\r?\n/).filter(l=>/Executer-Supabase|args=@\(/.test(l)).join('\n');
assert.doesNotMatch(commandes,/\b(?:db\s+(?:reset|push)|restore_project|apply_migration|delete_project)\b/i);
assert.doesNotMatch(s,/--db-url|--password|gh\s|git\s+push/i);
assert.doesNotMatch(s,/(?:service_role|postgresql:\/\/)/i,'No connection secrets embedded');
for(const arg of ['--schema','auth','storage','public'])assert.ok(s.includes(arg));
const doc=fs.readFileSync('docs/SAUVEGARDE_V1_GRATUITE.md','utf8');
assert.match(doc,/restauration isolée/i);
assert.match(doc,/ne remplace pas/i);
assert.match(doc,/Windows/);
assert.match(s,/Push-Location -LiteralPath \$dossier/);
assert.match(s,/\$env:SUPABASE_WORKDIR=\$dossier/);
assert.match(s,/Get-Content -LiteralPath \$lienLocal/);
assert.match(s,/Pop-Location/);
assert.match(s,/Select-String -LiteralPath \$chemin/);
assert.match(s,/verifier-archive-v1\.ps1/);
assert.match(s,/fichiers binaires Supabase Storage ne sont PAS inclus/);
const verify=fs.readFileSync('scripts/verifier-archive-v1.ps1','utf8');
assert.match(verify,/Get-FileHash -LiteralPath \$fichier -Algorithm SHA256/);
assert.match(verify,/function Compter-Copy/);
assert.match(verify,/\$profils -ne \$utilisateurs/);
assert.match(verify,/\$identites -lt \$utilisateurs/);
assert.match(verify,/fichierRestaurationValide/);
assert.doesNotMatch(verify,/(?:Invoke-WebRequest|Invoke-RestMethod|supabase link|db reset|db push|service_role)/i);
const mediaBackup=fs.readFileSync('scripts/sauvegarder-media-v1-prive.ps1','utf8');
assert.match(mediaBackup,/ss:\/\/\/tourneo-media/);
assert.match(mediaBackup,/storage cp/);
assert.match(mediaBackup,/--recursive --experimental --linked/);
assert.match(mediaBackup,/refLiee -cne \$projet/);
assert.match(mediaBackup,/Get-FileHash/);
assert.match(mediaBackup,/controle-storage-hash.json/);
assert.doesNotMatch(mediaBackup,/storage (?:rm|mv)|db (?:reset|push)|\bservice_role\b/i);
console.log('Archive V1 : opération lecture seule, fichiers locaux hors dépôt, Auth inclus, empreintes, aucune preuve inventée : OK');
